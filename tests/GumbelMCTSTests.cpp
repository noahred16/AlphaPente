PenteGame makeGame(std::initializer_list<std::pair<int, int>> moves) {
    PenteGame g(PenteGame::Config::pente());
    g.reset();
    for (auto [x, y] : moves) g.makeMove(x, y);
    return g;
}

// Black (to move) has an open four on row 9: x = 9..12. Winning moves: (8,9), (13,9).
PenteGame openFourPosition() {
    return makeGame({{9, 9}, {0, 0}, {12, 9}, {0, 3}, {11, 9}, {0, 6}, {10, 9}, {3, 0}});
}

// White (to move) must block at (13,9): black has four on row 9 with (8,9) already blocked.
PenteGame mustBlockPosition() {
    return makeGame({{9, 9}, {8, 9}, {12, 9}, {0, 3}, {11, 9}, {0, 6}, {10, 9}});
}

PenteGame midgamePosition() {
    return makeGame({{9, 9}, {10, 10}, {12, 9}, {8, 8}, {11, 11}, {9, 12}, {7, 9}, {13, 13}});
}

GumbelSearch::Config cfg(int n, int m, uint32_t seed = 7, int threads = 1) {
    GumbelSearch::Config c;
    c.tree.numSimulations = n;
    c.tree.maxConsideredActions = m;
    c.tree.seed = seed;
    c.numThreads = threads;
    return c;
}

// HeuristicEvaluator/UniformEvaluator values come from random rollouts, so they differ run to run.
// Tests that compare two searches need an evaluator that is a pure function of the position.
class DeterministicEvaluator : public Evaluator {
  public:
    std::pair<std::vector<std::pair<PenteGame::Move, float>>, float> evaluate(const PenteGame &game) override {
        return {evaluatePolicy(game), evaluateValue(game)};
    }
    std::vector<std::pair<PenteGame::Move, float>> evaluatePolicy(const PenteGame &game) override {
        return heuristic_.evaluatePolicy(game);
    }
    float evaluateValue(const PenteGame &game) override {
        return 0.5f * (static_cast<float>(game.getHash() % 2001) / 1000.0f - 1.0f);
    }

  private:
    HeuristicEvaluator heuristic_;
};

bool isMove(const PenteGame::Move &mv, int x, int y) { return mv.x == x && mv.y == y; }

void checkSeq(int m, int n, const std::vector<int> &expected) {
    INFO("m=" << m << " n=" << n);
    CHECK(GumbelTree::consideredVisitSequence(m, n) == expected);
}

void checkQ(double raw, std::vector<float> logits, std::vector<double> q, std::vector<int> visits,
            std::vector<float> expected) {
    std::vector<float> out(logits.size());
    GumbelTree::completedQValues(raw, logits.data(), q.data(), visits.data(), static_cast<int>(logits.size()), 50.0f,
                                 0.1f, out.data());
    for (size_t i = 0; i < out.size(); ++i) CHECK(out[i] == doctest::Approx(expected[i]).epsilon(1e-4));
}

